// Generates one migration per seed/cities-0NN.json file (more south Tamil Nadu city pages): 030_more_city_pages.sql, 031_...
// The JSON files are the single source: the web dev mock reads them too. Usage: node database/seed/build-cities.mjs
// Files are processed in order so display order continues across them; never change a file whose migration has been applied.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const catalog = JSON.parse(readFileSync(join(here, 'catalog.json'), 'utf8'));
const slugs = new Set(catalog.products.map((p) => p.slug));
const taken = new Set(catalog.cities.map((c) => c.slug));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`; // values are validated below: printable ASCII, no backslash

const names = { '030': 'more_city_pages', '031': 'third_city_group' };
let order = catalog.cities.length;
let leadOrder = catalog.leadTimes.length;
for (const file of readdirSync(here).filter((f) => /^cities-\d{3}\.json$/.test(f)).sort()) {
  const num = file.slice(7, 10);
  if (!names[num]) throw new Error(`${file}: add its migration name to build-cities.mjs`);
  const script = `${num}_${names[num]}.sql`;
  const cities = JSON.parse(readFileSync(join(here, file), 'utf8'));
  const rows = [];
  const leads = [];
  for (const c of cities) {
    if (!/^[a-z0-9-]+$/.test(c.slug) || taken.has(c.slug)) throw new Error(`${file}: bad or duplicate slug "${c.slug}"`);
    const text = JSON.stringify(c);
    if (/[^\x20-\x7e]/.test(text) || text.includes(String.fromCharCode(92))) throw new Error(`${file}: "${c.slug}" has a non-ASCII character or backslash`);
    if (c.zones.length > 300 || c.intro.length > 600) throw new Error(`${file}: "${c.slug}" zones or intro too long`);
    for (const s of c.pop) if (!slugs.has(s)) throw new Error(`${file}: "${c.slug}" lists unknown product "${s}"`);
    taken.add(c.slug);
    order += 1;
    rows.push(` (${[c.slug, c.name].map(q).join(',')},${c.km},${[c.lead, c.zones, c.intro, JSON.stringify(c.inds), JSON.stringify(c.pop)].map(q).join(',')},${order})`);
    leads.push(` (${q(c.name)},${q(c.lead)},${(leadOrder += 1)})`);
  }

  writeFileSync(join(here, '../migrations', script), `-- =====================================================================
-- ${script}  -  ${rows.length} more south Tamil Nadu city pages (/steel-suppliers-{slug}/): ${cities.map((c) => c.name).join(', ')}.
-- GENERATED by database/seed/build-cities.mjs from seed/${file}. Do not edit by hand.
-- INSERT IGNORE: a city that already exists (added or edited in the admin) is left alone. Distances, lead times and
-- zones are TO CONFIRM with the owner; staff can edit or unpublish each page under admin > Pages & content. Safe to re-run.
-- =====================================================================
INSERT IGNORE INTO \`Cities\` (\`Slug\`,\`Name\`,\`DistanceKm\`,\`LeadTime\`,\`Zones\`,\`Intro\`,\`IndustriesJson\`,\`PopularSlugsJson\`,\`DisplayOrder\`) VALUES
${rows.join(',\n')};

INSERT IGNORE INTO \`DeliveryLeadTimes\` (\`City\`,\`LeadTime\`,\`DisplayOrder\`) VALUES
${leads.join(',\n')};

INSERT INTO \`__schema_migrations\` (\`script_name\`)
SELECT '${script}'
WHERE NOT EXISTS (SELECT 1 FROM \`__schema_migrations\` WHERE \`script_name\` = '${script}');
`);
  console.log(`${script}: ${rows.length} cities`);
}
