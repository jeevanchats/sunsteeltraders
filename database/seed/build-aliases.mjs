// Generates migrations/026_product_aliases.sql from seed/aliases.json (slug -> trade names customers search for).
// aliases.json is the single source: the web dev mock reads it too. Usage: node database/seed/build-aliases.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const aliases = JSON.parse(readFileSync(join(here, 'aliases.json'), 'utf8'));
const catalog = JSON.parse(readFileSync(join(here, 'catalog.json'), 'utf8'));
const slugs = new Set(catalog.products.map((p) => p.slug));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`; // values are validated below: printable ASCII, no comma, no backslash

const rows = [];
for (const [slug, list] of Object.entries(aliases)) {
  if (!slugs.has(slug)) throw new Error(`aliases.json: unknown product slug "${slug}"`);
  if (list.some((a) => /[^\x20-\x7e]/.test(a) || a.includes(',') || a.includes(String.fromCharCode(92)))) throw new Error(`aliases.json: "${slug}" has a non-ASCII character, comma or backslash`);
  const text = list.join(', ');
  if (text.length > 400) throw new Error(`aliases.json: "${slug}" is longer than 400 characters`);
  rows.push(`    UPDATE \`Products\` SET \`Aliases\` = ${q(text)} WHERE \`Slug\` = ${q(slug)};`);
}

writeFileSync(join(here, '../migrations/026_product_aliases.sql'), `-- =====================================================================
-- 026_product_aliases.sql  -  Products.Aliases: the trade names customers search for ("MS polish rod", "I beam", "Teflon bush"),
-- shown as "Also called" on the product page, in its FAQ, in the site search and in the page's structured data.
-- GENERATED by database/seed/build-aliases.mjs from seed/aliases.json. Do not edit by hand.
-- ${rows.length} products get a starting list. The seeding runs only when the column is first added, so names staff edit or clear
-- in the admin are never put back by a later deploy. Safe to re-run.
-- =====================================================================
DROP PROCEDURE IF EXISTS \`_m026_product_aliases\`;
DELIMITER //
CREATE PROCEDURE \`_m026_product_aliases\`()
BEGIN
  -- MySQL 8 has no ADD COLUMN IF NOT EXISTS: skip the whole block when it already ran.
  IF NOT EXISTS (SELECT 1 FROM information_schema.COLUMNS
                  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'Products' AND COLUMN_NAME = 'Aliases') THEN
    ALTER TABLE \`Products\` ADD COLUMN \`Aliases\` VARCHAR(400) NULL AFTER \`Applications\`;
${rows.join('\n')}
  END IF;
END//
DELIMITER ;
CALL \`_m026_product_aliases\`();
DROP PROCEDURE \`_m026_product_aliases\`;

INSERT INTO \`__schema_migrations\` (\`script_name\`)
SELECT '026_product_aliases.sql'
WHERE NOT EXISTS (SELECT 1 FROM \`__schema_migrations\` WHERE \`script_name\` = '026_product_aliases.sql');
`);
console.log(`026_product_aliases.sql: ${rows.length} products`);
